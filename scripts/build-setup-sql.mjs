// Builds supabase/setup.sql = every migration (in order) + seed.sql, so the whole database can be set up
// (or brought up to date) with ONE paste into the Supabase SQL Editor. Every part is safe to re-run.
// Usage: npm run db:setup-sql   (a unit test fails if setup.sql is out of date)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export function buildSetupSql(root = process.cwd()) {
  const dir = join(root, "supabase", "migrations");
  const parts = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort()
    .map((f) => `-- ===================================================================\n-- ${f}\n-- ===================================================================\n${readFileSync(join(dir, f), "utf8").trim()}\n`);
  parts.push(`-- ===================================================================\n-- seed.sql (FUJ starting values; keeps anything already set)\n-- ===================================================================\n${readFileSync(join(root, "supabase", "seed.sql"), "utf8").trim()}\n`);
  return `-- FlagUpJesus — complete database setup (GENERATED by scripts/build-setup-sql.mjs; do not edit by hand).
-- Paste ALL of this into Supabase → SQL Editor → New query → Run.
-- Safe on a brand-new project AND on one that already ran some or all migrations: it only adds what's missing.

${parts.join("\n")}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(join(process.cwd(), "supabase", "setup.sql"), buildSetupSql());
  console.log("Wrote supabase/setup.sql");
}
