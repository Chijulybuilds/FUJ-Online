const buckets = (globalThis as unknown as { __fujRate?: Map<string, { count: number; reset: number }> }).__fujRate ??= new Map();

/** Fixed-window in-memory limiter. Good enough for a single instance; use a shared store when scaling out. */
export function rateLimit(key: string, limit: number, windowMs: number): boolean {
  const now = Date.now();
  const bucket = buckets.get(key);
  if (!bucket || bucket.reset < now) {
    buckets.set(key, { count: 1, reset: now + windowMs });
    return true;
  }
  bucket.count += 1;
  return bucket.count <= limit;
}

export function clientIp(headers: Headers) {
  return headers.get("x-forwarded-for")?.split(",")[0]?.trim() || headers.get("x-real-ip") || "local";
}
